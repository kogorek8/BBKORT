const DICT = { pl, en };
let lang = 'pl';
try { lang = localStorage.getItem('bbkort_lang') || 'pl'; } catch { /* ignore */ }

export const getLang = () => lang;
export function setLang(l) {
  lang = DICT[l] ? l : 'pl';
  try { localStorage.setItem('bbkort_lang', lang); } catch { /* ignore */ }
}
export const has = (k) => k in pl;
export function t(k, vars) {
  let s = DICT[lang][k] ?? pl[k] ?? k;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, n) => vars[n] ?? '');
  return s;
}
